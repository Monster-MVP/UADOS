def version(state):
    return state.get("protocol_version", 1)


def extend_state(state):
    for name in COLLECTIONS:
        state.setdefault(name, {})


def task_version(task):
    return task.get("protocol_version", 1)


def spec(task):
    return {name: task[name] for name in ("title", "description", "risk", "scope", "depends")}


def render_enterprise(state):
    if version(state) < 2:
        return {}
    banner = "<!-- Generated by UADOS from the ledger. Use CLI commands; do not edit. -->\n\n"
    def document(title, records):
        text = "# " + title + "\n\n"
        if not records:
            text += "No records yet. Absence of records does not establish a finding.\n"
        for record in records:
            text += "## %s\n\n```json\n%s\n```\n\n" % (record["id"], json.dumps(record, indent=2, ensure_ascii=False, sort_keys=True))
        return banner + text
    debates = list(state.get("debates", {}).values())
    consensus = [d for d in debates if d.get("consensus")]
    result = {
        "CONSENSUS_DECISION.md": document("Consensus decisions", consensus),
        "SYSTEM_IMPROVEMENT_LOG.md": document("System improvement log", list(state.get("improvements", {}).values())),
        "MULTI_AGENT_SYSTEM/role_plans.md": document("Generated role plans and assignments", list(state.get("role_plans", {}).values())),
        "RESEARCH_MANAGEMENT/NOVELTY_AUDIT.md": document("Research novelty audits", list(state.get("ideas", {}).values())),
        "RESEARCH_MANAGEMENT/LITERATURE_GAP_ANALYSIS.md": document("Literature gap analysis", list(state.get("literature", {}).values()) + list(state.get("ideas", {}).values())),
        "RESEARCH_MANAGEMENT/RESEARCH_DECISION_RECORD.md": document("Research decisions", list(state.get("ideas", {}).values())),
        "RESEARCH_MANAGEMENT/HYPOTHESES.md": document("Falsifiable hypotheses and exact run outcomes", list(state.get("hypotheses", {}).values())),
    }
    for change in state.get("changes", {}).values():
        result["CHANGE_REQUESTS/" + change["id"] + ".md"] = document("Change request " + change["id"], [change])
    return result


def all_evidence(state):
    """Include nested historical records: review proof must survive export and audit."""
    records = []
    def visit(value):
        if isinstance(value, dict):
            if {"path", "sha256", "bytes"}.issubset(value):
                records.append(value)
            else:
                for item in value.values():
                    visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)
    for name in COLLECTIONS + ("tasks", "decisions", "experiments"):
        visit(state.get(name, {}))
    return records


def current_evidence(state):
    """Explicit live bindings, separated from retained superseded records."""
    selected = dict(state)
    selected["tasks"] = {key: {"evidence": task["evidence"], "plan": task.get("plan")} for key, task in state["tasks"].items()}
    selected["changes"] = {key: change for key, change in state.get("changes", {}).items() if any(task.get("change") == key for task in state["tasks"].values())}
    selected["debates"] = {key: debate for key, debate in state.get("debates", {}).items()
        if (debate["role_plan"] == state["tasks"][debate["task"]].get("role_plan")
            and debate.get("task_revision") == state["tasks"][debate["task"]]["revision"])}
    return all_evidence(selected)


def ensure_v2(state):
    if version(state) < 2:
        raise UadosError("This operation requires protocol2. Explicitly upgrade the project under an owned, reviewed major task.")
    extend_state(state)
